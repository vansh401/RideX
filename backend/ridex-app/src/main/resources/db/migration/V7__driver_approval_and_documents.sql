-- Step 3.3: the approval workflow and driver documents.

-- Who decided, when, and why. NULL until a decision has been made.
ALTER TABLE driver_profiles
    ADD COLUMN rejection_reason VARCHAR(255),
    ADD COLUMN reviewed_by      UUID REFERENCES users (id),
    ADD COLUMN reviewed_at      TIMESTAMPTZ,
    -- Optimistic locking: two admins deciding on the same profile cannot both win
    ADD COLUMN version          BIGINT NOT NULL DEFAULT 0;

-- The admin review queue filters by status and reads oldest first
CREATE INDEX idx_driver_profiles_status_created ON driver_profiles (approval_status, created_at);

-- File METADATA lives in the database; the file itself lives in storage (disk now, object storage
-- later). The database never holds the bytes.
CREATE TABLE driver_documents (
    id                UUID         PRIMARY KEY,
    driver_profile_id UUID         NOT NULL REFERENCES driver_profiles (id) ON DELETE CASCADE,
    type              VARCHAR(30)  NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    content_type      VARCHAR(100) NOT NULL,
    size_bytes        BIGINT       NOT NULL,
    -- Where the file is stored. Generated by us (never taken from the client).
    storage_key       VARCHAR(255) NOT NULL UNIQUE,
    uploaded_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_driver_documents_type
        CHECK (type IN ('DRIVING_LICENSE', 'VEHICLE_REGISTRATION', 'INSURANCE', 'ID_PROOF')),
    CONSTRAINT chk_driver_documents_size CHECK (size_bytes > 0),
    -- One document per type per driver: uploading again replaces it.
    -- This index also serves "all documents of a profile" (its leading column).
    CONSTRAINT uq_driver_documents_type UNIQUE (driver_profile_id, type)
);
