package com.ridex.ridex_app.driver;

import java.util.List;
import java.util.UUID;

import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.transaction.support.TransactionSynchronization;
import org.springframework.transaction.support.TransactionSynchronizationManager;

import com.ridex.ridex_app.common.ConflictException;
import com.ridex.ridex_app.common.ResourceNotFoundException;
import com.ridex.ridex_app.common.UnsupportedFileException;
import com.ridex.ridex_app.storage.FileSignature;
import com.ridex.ridex_app.storage.FileStorage;
import com.ridex.ridex_app.user.UserService;

@Service
public class DriverDocumentService {

    static final long MAX_BYTES = 5L * 1024 * 1024;

    private final DriverProfileRepository profileRepository;
    private final DriverDocumentRepository documentRepository;
    private final FileStorage storage;
    private final UserService userService;

    public DriverDocumentService(DriverProfileRepository profileRepository,
                                 DriverDocumentRepository documentRepository,
                                 FileStorage storage,
                                 UserService userService) {
        this.profileRepository = profileRepository;
        this.documentRepository = documentRepository;
        this.storage = storage;
        this.userService = userService;
    }

    /**
     * Stores a document for the calling driver. Uploading the same type again REPLACES the old
     * one. The file content is checked (size, real format from its bytes), the stored name is
     * generated by us, and files are never kept for an APPROVED profile's locked paperwork.
     */
    @Transactional
    public DocumentResponse upload(UUID userId, DocumentType type, String originalFilename, byte[] content) {
        userService.getActiveUser(userId);
        DriverProfile profile = profileOf(userId);
        requireEditable(profile);

        if (content == null || content.length == 0) {
            throw new UnsupportedFileException("The file is empty");
        }
        if (content.length > MAX_BYTES) {
            throw new UnsupportedFileException("The file is larger than 5 MB");
        }
        FileSignature.Detected detected = FileSignature.detect(content)
                .orElseThrow(() -> new UnsupportedFileException("Only PDF, JPEG and PNG files are accepted"));

        String key = storage.store("driver-documents/" + profile.getId(), detected.extension(), content);
        // If the database transaction fails after the file was written, do not leave an orphan file
        runOnRollback(() -> storage.delete(key));

        documentRepository.findByDriverProfileIdAndType(profile.getId(), type).ifPresent(old -> {
            documentRepository.delete(old);
            // Remove the replaced file only once the new row is really committed
            runAfterCommit(() -> storage.delete(old.getStorageKey()));
        });
        documentRepository.flush();   // delete-then-insert of the same (profile, type) in one transaction

        DriverDocument saved = documentRepository.save(new DriverDocument(
                profile, type, cleanFilename(originalFilename), detected.contentType(), content.length, key));
        return DocumentResponse.from(saved);
    }

    @Transactional(readOnly = true)
    public List<DocumentResponse> list(UUID userId) {
        return documentRepository.findByDriverProfileIdOrderByUploadedAtAsc(profileOf(userId).getId())
                .stream().map(DocumentResponse::from).toList();
    }

    @Transactional
    public void delete(UUID userId, UUID documentId) {
        userService.getActiveUser(userId);
        DriverProfile profile = profileOf(userId);
        requireEditable(profile);
        DriverDocument document = documentRepository.findByIdAndDriverProfileId(documentId, profile.getId())
                .orElseThrow(() -> new ResourceNotFoundException("Document not found"));
        documentRepository.delete(document);
        runAfterCommit(() -> storage.delete(document.getStorageKey()));
    }

    @Transactional(readOnly = true)
    public DocumentFile fileOfDriver(UUID userId, UUID documentId) {
        return fileOf(profileOf(userId).getId(), documentId);
    }

    /** Used by the admin review: the document must belong to the profile named in the URL. */
    @Transactional(readOnly = true)
    public DocumentFile fileOf(UUID profileId, UUID documentId) {
        DriverDocument document = documentRepository.findByIdAndDriverProfileId(documentId, profileId)
                .orElseThrow(() -> new ResourceNotFoundException("Document not found"));
        return new DocumentFile(document.getOriginalFilename(), document.getContentType(),
                storage.read(document.getStorageKey()));
    }

    private DriverProfile profileOf(UUID userId) {
        return profileRepository.findByUserId(userId)
                .orElseThrow(() -> new ResourceNotFoundException("Create your driver profile first"));
    }

    private void requireEditable(DriverProfile profile) {
        if (profile.isApproved()) {
            throw new ConflictException("Documents are locked once the profile is APPROVED");
        }
    }

    /** Keep only the last path segment, drop control characters, cap the length. Display only. */
    static String cleanFilename(String name) {
        String value = name == null ? "" : name;
        value = value.substring(Math.max(value.lastIndexOf('/'), value.lastIndexOf('\\')) + 1);
        value = value.replaceAll("\\p{Cntrl}", "").trim();
        if (value.isEmpty()) {
            return "document";
        }
        return value.length() > 255 ? value.substring(0, 255) : value;
    }

    private static void runAfterCommit(Runnable action) {
        if (TransactionSynchronizationManager.isSynchronizationActive()) {
            TransactionSynchronizationManager.registerSynchronization(new TransactionSynchronization() {
                @Override
                public void afterCommit() {
                    action.run();
                }
            });
        } else {
            action.run();
        }
    }

    private static void runOnRollback(Runnable action) {
        if (TransactionSynchronizationManager.isSynchronizationActive()) {
            TransactionSynchronizationManager.registerSynchronization(new TransactionSynchronization() {
                @Override
                public void afterCompletion(int status) {
                    if (status == STATUS_ROLLED_BACK) {
                        action.run();
                    }
                }
            });
        }
    }
}
